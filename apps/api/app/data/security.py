from app.domain.enums import Environment, Provider, Region, cluster_name
from app.domain.models import CertificateRecord, SecretHistoryEvent, SecretRecord


def _scope(provider: Provider, region: Region, environment: Environment) -> dict[str, str]:
    return {
        "provider": provider,
        "region": region,
        "environment": environment,
        "cluster": cluster_name(provider, region, environment),
    }


def _history(*events: dict[str, str]) -> list[SecretHistoryEvent]:
    return [SecretHistoryEvent.model_validate(event) for event in events]


