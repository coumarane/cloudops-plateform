def _secret(
    secret_id: str,
    name: str,
    namespace: str,
    provider: Provider,
    region: Region,
    environment: Environment,
    account: str,
    status: str,
    last_rotated: str,
    next_due: str,
    last_validated: str,
    history: list[SecretHistoryEvent],
) -> SecretRecord:
    return SecretRecord(
        id=secret_id,
        name=name,
        namespace=namespace,
        provider=provider,
        region=region,
        environment=environment,
        account=account,
        status=status,  # type: ignore[arg-type]
        lastRotated=last_rotated,
        nextDue=next_due,
        lastValidated=last_validated,
        history=history,
    )


